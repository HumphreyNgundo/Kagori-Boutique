#!/usr/bin/env node
/**
 * Scans public/products/<slug>/ and regenerates src/lib/media-manifest.ts.
 * Run after adding photos:  npm run media:manifest
 */
import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(process.cwd(), "public", "products");
const OUT = join(process.cwd(), "src", "lib", "media-manifest.ts");
const IMAGE = /\.(jpe?g|png|webp|avif)$/i;

if (!existsSync(ROOT)) mkdirSync(ROOT, { recursive: true });

const manifest = {};
for (const slug of readdirSync(ROOT)) {
  const dir = join(ROOT, slug);
  if (!statSync(dir).isDirectory()) continue;
  const files = readdirSync(dir)
    .filter((f) => IMAGE.test(f))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  if (files.length) manifest[slug] = files.map((f) => `/products/${slug}/${f}`);
}

const body = `/**
 * Generated by \`npm run media:manifest\` — do not edit by hand.
 *
 * Drop product photos into public/products/<product-slug>/ (jpg|jpeg|png|webp|avif),
 * run the script, and the storefront picks them up. Products with no folder
 * fall back to generated studio art, so the catalogue is never broken.
 */
export const MEDIA_MANIFEST: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync(OUT, body);
console.log(`media-manifest: ${Object.keys(manifest).length} product folder(s)`);
